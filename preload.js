'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  openPack: () => ipcRenderer.invoke('pack:open'),
  scanPack: (folder) => ipcRenderer.invoke('pack:scan', folder),
  loadMesh: (ydd) => ipcRenderer.invoke('mesh:load', ydd),
  loadTexture: (ytd) => ipcRenderer.invoke('tex:load', ytd),
  saveTexture: (ytd, rgba, opts) => ipcRenderer.invoke('tex:save', ytd, rgba, opts),
  addVariant: (ytd, usedLetters) => ipcRenderer.invoke('variant:add', ytd, usedLetters),
  deleteVariant: (ytd) => ipcRenderer.invoke('variant:delete', ytd),
  pickYdd: () => ipcRenderer.invoke('ydd:pick'),
  registerYdd: (paths) => ipcRenderer.invoke('ydd:register', paths),
  pickTextures: () => ipcRenderer.invoke('tex:pick'),
  registerTextures: (paths) => ipcRenderer.invoke('tex:register', paths),
  fileDataUrl: (token) => ipcRenderer.invoke('file:dataUrl', token),
  pieceTemplate: (root, gender, prop, comp, itemId) => ipcRenderer.invoke('piece:template', root, gender, prop, comp, itemId),
  pieceOptions: (root, itemId) => ipcRenderer.invoke('piece:options', root, itemId),
  pieceSetOptions: (root, itemId, opts) => ipcRenderer.invoke('piece:setOptions', root, itemId, opts),
  pieceAdd: (root, spec) => ipcRenderer.invoke('piece:add', root, spec),
  pieceAddTextures: (root, itemId, textures) => ipcRenderer.invoke('piece:addTextures', root, itemId, textures),
  pieceDelete: (root, itemId) => ipcRenderer.invoke('piece:delete', root, itemId),
  pieceMove: (root, itemId, to) => ipcRenderer.invoke('piece:move', root, itemId, to),
  packNew: (name) => ipcRenderer.invoke('pack:new', name),
  packBuild: (root, name) => ipcRenderer.invoke('pack:build', root, name),
  ymtStatus: (root) => ipcRenderer.invoke('ymt:status', root),
  ymtSync: (root, opts) => ipcRenderer.invoke('ymt:sync', root, opts),
  savePng: (name, dataUrl) => ipcRenderer.invoke('png:save', name, dataUrl),
  saveProject: (name, json) => ipcRenderer.invoke('project:save', name, json),
  openProject: () => ipcRenderer.invoke('project:open'),
  openImage: () => ipcRenderer.invoke('image:open'),
  bodyStatus: () => ipcRenderer.invoke('body:status'),
  bodySetDir: () => ipcRenderer.invoke('body:setDir'),
  bodyLoad: (gender) => ipcRenderer.invoke('body:load', gender),
  onBodyProgress: (cb) => { ipcRenderer.on('body:progress', (_e, text) => cb(text)); },
  setFullscreen: (on) => ipcRenderer.invoke('win:fullscreen', !!on),
  viewerOpen: () => ipcRenderer.invoke('viewer:open'),
  viewerClose: () => ipcRenderer.invoke('viewer:close'),
  viewerSend: (msg) => ipcRenderer.send('viewer:send', msg),
  onViewerMessage: (cb) => { ipcRenderer.on('viewer:msg', (_e, msg) => cb(msg)); },
  // the real path of a dragged-in file; main remembers it so only genuinely dropped paths can be opened later
  pathForFile: (file) => { const p = webUtils.getPathForFile(file); if (p) ipcRenderer.send('drop:path', p); return p; },
  isDesktop: true,
});
